import { boot, choose, ROOT } from './harness.mjs';
import { pathToFileURL } from 'url';
const w = boot({ 'scrabble.theme': 'pink' });
const ctx = new Proxy(function () {}, { get: (t, p) => (p === 'then' ? undefined : ctx), apply: () => ctx, set: () => true });
w.document.fonts = { load: () => Promise.resolve(), ready: Promise.resolve() }; globalThis.devicePixelRatio = 1; globalThis.addEventListener = (...a) => w.addEventListener(...a); globalThis.removeEventListener = (...a) => w.removeEventListener(...a);
w.HTMLCanvasElement.prototype.getContext = () => ctx;
w.requestAnimationFrame = f => setTimeout(f, 16); globalThis.requestAnimationFrame = w.requestAnimationFrame; globalThis.cancelAnimationFrame = clearTimeout;
globalThis.matchMedia = w.matchMedia = () => ({ matches: false, addEventListener() {}, addListener() {} });
globalThis.ResizeObserver = class { observe() {} disconnect() {} };
w.ResizeObserver = globalThis.ResizeObserver;
let errors = []; process.on('uncaughtException', e => errors.push(e)); process.on('unhandledRejection', e => errors.push(e));
console.log('importing main'); await import(pathToFileURL(`${ROOT}/js/main.js`).href); console.log('main imported');
console.log('waiting'); await new Promise(r => setTimeout(r, 100)); console.log('waited');
const d = w.document;
let pass = 0, fail = 0; const ok = (c, m) => { if (c) pass++; else { fail++; console.log('FAIL:', m); } };
ok(errors.length === 0, 'no startup errors: ' + errors.map(e => e.message).join('; '));
ok(d.documentElement.dataset.theme === 'pink', 'saved theme restored at startup');
ok(!d.querySelector('#cover').hidden, 'cover visible');
ok(d.querySelector('#coverTitle').textContent.replace(/\s/g, '').toUpperCase().includes('ARABIC'), 'cover title built');
ok(d.querySelector('.coverSub').textContent === 'INTEGRATED VERSION', 'cover branding');
d.querySelector('#coverPlay').click(); await new Promise(r => setTimeout(r, 800));
ok(d.querySelector('#md').open, 'PLAY opens mode selection');
const btns = [...d.querySelectorAll('#mf .modeBtn')];
ok(btns.length === 3 && btns[0].textContent.includes('الحروف الموسعة') && btns[0].textContent.includes('Expanded') && btns[0].textContent.includes('أ إ آ ء ؤ ئ ة ى') && btns.some(b => b.textContent.includes('الألف المرنة')) && btns.at(-1).textContent.includes('الحروف الأساسية') && btns.at(-1).textContent.includes('Basic'), 'mode dialog content: ' + btns.map(b => b.textContent).join(' | '));
choose('#md', 'basic'); choose('#sd', '25'); choose('#dlg', 'ok');
ok(d.querySelector('#bagInfo').textContent.startsWith('الحروف الأساسية'), 'game started in basic via the real entry point');
// settings dialog
d.querySelector('#bSettings').click();
ok(d.querySelector('#ad').open, 'settings opens'); 
const heads = [...d.querySelectorAll('#ad .setH')].map(h => h.textContent);
ok(heads[0].startsWith('الأساسيات') && ['المظهر', 'التخطيط', 'الرسوميات'].every(x => heads.some(h => h.startsWith(x))), 'settings sections: ' + heads.join(' | '));
ok(d.querySelectorAll('#thB .thOpt').length === 4, '4 theme options');
const rows = d.querySelectorAll('#lyB .segRow');
ok(rows.length === 7 && [...rows].every(r => r.querySelectorAll('button[data-v]').length >= 2), `${rows.length} layout rows, each with its choices`);
ok(!/صوت|موسيقى|كتم|سماعة/.test(d.querySelector('#ad').textContent), 'no audio text in settings');
const { S } = await import(pathToFileURL(`${ROOT}/js/state.js`).href);
ok(S.paused === true, 'clock paused while settings open');
d.querySelector('#thB .thOpt[data-theme="desert"]').click();
ok(d.documentElement.dataset.theme === 'desert' && S.board && !S.ended, 'theme switch live in settings');
d.querySelector('#ad').close(''); ok(S.paused === false, 'clock resumes after settings');
console.log(`${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
